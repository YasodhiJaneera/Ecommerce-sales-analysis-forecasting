"""##  Import libraries and load data"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import os

sns.set_theme(style="whitegrid")

# Updated path to load the file from the root directory where it was uploaded
analysis_data = pd.read_csv(
    "cleaned_merged_dataset.csv"
)

analysis_data["order_date"] = pd.to_datetime(
    analysis_data["order_date"]
)

print("Dataset loaded:", analysis_data.shape)
display(analysis_data.head())

"""##  Descriptive statistics"""

display(analysis_data.describe())

"""##  Revenue and profit summary"""

total_revenue = analysis_data["total_revenue_gbp"].sum()
total_profit = analysis_data["net_profit_gbp"].sum()
total_orders = analysis_data["order_id"].nunique()

print(f"Total Revenue: £{total_revenue:,.2f}")
print(f"Total Profit: £{total_profit:,.2f}")
print(f"Total Orders: {total_orders:,}")

"""##  Monthly sales trends"""

monthly_sales = (
    analysis_data.groupby(
        analysis_data["order_date"].dt.to_period("M")
    )["total_revenue_gbp"]
    .sum()
)

monthly_sales.index = monthly_sales.index.to_timestamp()

plt.figure(figsize=(12, 6))
plt.plot(monthly_sales.index, monthly_sales.values, marker="o")

plt.title("Monthly Sales Revenue Trend")
plt.xlabel("Month")
plt.ylabel("Revenue (£)")
plt.xticks(rotation=45)
plt.tight_layout()

# Automatically create the directories if they do not exist
os.makedirs("/content/reports/figures/eda/", exist_ok=True)

plt.savefig(
    "/content/reports/figures/eda/monthly_sales_trend.png",
    dpi=300,
    bbox_inches="tight"
)
plt.show()

"""##  Sales distribution"""

plt.figure(figsize=(10, 6))

sns.histplot(
    analysis_data["total_revenue_gbp"],
    bins=30,
    kde=True
)

plt.title("Distribution of Revenue")
plt.xlabel("Revenue (£)")
plt.ylabel("Frequency")
plt.tight_layout()
plt.show()

"""##  Boxplot of revenue"""

plt.figure(figsize=(10, 5))

sns.boxplot(
    x=analysis_data["total_revenue_gbp"]
)

plt.title("Revenue Distribution and Outliers")
plt.xlabel("Revenue (£)")
plt.tight_layout()
plt.show()

"""##  Quantity distribution"""

plt.figure(figsize=(10, 5))

sns.histplot(
    analysis_data["quantity"],
    bins=20,
    kde=True
)

plt.title("Product Quantity Distribution")
plt.xlabel("Quantity")
plt.ylabel("Frequency")
plt.tight_layout()
plt.show()

"""##  Sales by category

Use the correct category column from the products dataset. After merging, it will usually be category.
"""

category_sales = (
    analysis_data.groupby("category")["total_revenue_gbp"]
    .sum()
    .sort_values(ascending=False)
)

plt.figure(figsize=(12, 6))
category_sales.plot(kind="bar")

plt.title("Revenue by Product Category")
plt.xlabel("Category")
plt.ylabel("Revenue (£)")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

display(category_sales)

"""##  Profit by category"""

category_profit = (
    analysis_data.groupby("category")["net_profit_gbp"]
    .sum()
    .sort_values(ascending=False)
)

plt.figure(figsize=(12, 6))
category_profit.plot(kind="bar")

plt.title("Profit by Product Category")
plt.xlabel("Category")
plt.ylabel("Profit (£)")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

"""##  Top 10 products by revenue"""

top_products = (
    analysis_data.groupby("product_name")["total_revenue_gbp"]
    .sum()
    .sort_values(ascending=False)
    .head(10)
)

plt.figure(figsize=(12, 6))
top_products.sort_values().plot(kind="barh")

plt.title("Top 10 Products by Revenue")
plt.xlabel("Revenue (£)")
plt.ylabel("Product")
plt.tight_layout()
plt.show()

display(top_products)

"""##  Revenue by region"""

region_sales = (
    analysis_data.groupby("region")["total_revenue_gbp"]
    .sum()
    .sort_values(ascending=False)
)

plt.figure(figsize=(10, 6))
region_sales.plot(kind="bar")

plt.title("Revenue by Region")
plt.xlabel("Region")
plt.ylabel("Revenue (£)")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

display(region_sales)

"""##  Discount versus revenue"""

plt.figure(figsize=(10, 6))

sns.scatterplot(
    data=analysis_data,
    x="discount_pct",
    y="total_revenue_gbp"
)

plt.title("Discount Percentage vs Revenue")
plt.xlabel("Discount")
plt.ylabel("Revenue (£)")
plt.tight_layout()
plt.show()

"""##  Discount versus profit"""

plt.figure(figsize=(10, 6))

sns.scatterplot(
    data=analysis_data,
    x="discount_pct",
    y="net_profit_gbp"
)

plt.title("Discount Percentage vs Profit")
plt.xlabel("Discount")
plt.ylabel("Profit (£)")
plt.tight_layout()
plt.show()

"""##  Correlation heatmap"""

numeric_data = analysis_data.select_dtypes(
    include=np.number
)

correlation_matrix = numeric_data.corr()

plt.figure(figsize=(12, 8))

sns.heatmap(
    correlation_matrix,
    annot=True,
    cmap="coolwarm",
    fmt=".2f"
)

plt.title("Correlation Matrix")
plt.tight_layout()
plt.show()

"""##  Sales by day of week"""

analysis_data["day_name"] = (
    analysis_data["order_date"].dt.day_name()
)

weekday_order = [
    "Monday", "Tuesday", "Wednesday",
    "Thursday", "Friday", "Saturday", "Sunday"
]

weekday_sales = (
    analysis_data.groupby("day_name")["total_revenue_gbp"]
    .sum()
    .reindex(weekday_order)
)

plt.figure(figsize=(10, 6))
weekday_sales.plot(kind="bar")

plt.title("Sales by Day of Week")
plt.xlabel("Day")
plt.ylabel("Revenue (£)")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

