import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import os
import zipfile
import warnings

warnings.filterwarnings("ignore")
sns.set_theme(style="whitegrid")

print("Libraries imported successfully!")

"""# Upload dataset"""

from google.colab import files
uploaded = files.upload()

"""# Extract ZIP file"""

zip_filename = list(uploaded.keys())[0]

raw_folder = "/content/data/raw"
os.makedirs(raw_folder, exist_ok=True)

with zipfile.ZipFile(zip_filename, "r") as zip_ref:
    zip_ref.extractall(raw_folder)

print("Extraction completed!")

"""# Find CSV files"""

csv_files = {}

# Using raw_folder which was defined in the extraction step
for root, dirs, filenames in os.walk(raw_folder):
    for filename in filenames:
        if filename.lower().endswith(".csv"):
            csv_files[filename.lower()] = os.path.join(root, filename)

print("Available CSV files:")
for filename in csv_files:
    print(filename)

"""#  Preview datasets"""

# Load the CSV files into DataFrames
orders = pd.read_csv(csv_files['orders.csv'])
customers = pd.read_csv(csv_files['customers.csv'])
products = pd.read_csv(csv_files['products.csv'])
data_dictionary = pd.read_csv(csv_files['data_dictionary.csv'])

print("ORDERS")
display(orders.head())

print("CUSTOMERS")
display(customers.head())

print("PRODUCTS")
display(products.head())

print("DATA DICTIONARY")
display(data_dictionary.head())

"""#  Dataset dimensions"""

print("Orders shape:", orders.shape)
print("Customers shape:", customers.shape)
print("Products shape:", products.shape)
print("Data Dictionary shape:", data_dictionary.shape)

"""#  Column names"""

for name, df in {
    "Orders": orders,
    "Customers": customers,
    "Products": products
}.items():

    print(f"\n{name} columns:")
    print(df.columns.tolist())

"""#  Data types and information"""

print("ORDERS INFORMATION")
orders.info()

print("\nCUSTOMERS INFORMATION")
customers.info()

print("\nPRODUCTS INFORMATION")
products.info()

"""# Missing values"""

for name, df in {
    "Orders": orders,
    "Customers": customers,
    "Products": products
}.items():

    print(f"\nMissing values in {name}")
    display(df.isnull().sum())

"""#  Duplicate records"""

print("Orders duplicates:", orders.duplicated().sum())
print("Customers duplicates:", customers.duplicated().sum())
print("Products duplicates:", products.duplicated().sum())

"""#  Descriptive statistics"""

print("Orders statistical summary")
display(orders.describe(include="all"))

print("Customers statistical summary")
display(customers.describe(include="all"))

print("Products statistical summary")
display(products.describe(include="all"))

"""#  Date range"""

orders["order_date"] = pd.to_datetime(
    orders["order_date"],
    errors="coerce"
)

print("Start date:", orders["order_date"].min())
print("End date:", orders["order_date"].max())
print("Total days:", orders["order_date"].nunique())

"""#  Unique values in categorical columns"""

categorical_columns = [
    "shipping_mode",
    "payment_method",
    "order_status"
]

for column in categorical_columns:
    if column in orders.columns:
        print(f"\n{column}")
        print(orders[column].value_counts(dropna=False))

"""# Records per month"""

monthly_records = (
    orders.set_index("order_date")
    .resample("ME")
    .size()
)

plt.figure(figsize=(12, 5))
monthly_records.plot(kind="bar")

plt.title("Number of Order Records per Month")
plt.xlabel("Month")
plt.ylabel("Number of Records")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

