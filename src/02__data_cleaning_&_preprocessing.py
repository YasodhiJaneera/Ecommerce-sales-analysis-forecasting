"""##  Create data quality report function"""

def data_quality_report(df, dataset_name):

    report = pd.DataFrame({
        "Column": df.columns,
        "Data_Type": df.dtypes.astype(str).values,
        "Missing_Count": df.isnull().sum().values,
        "Missing_Percentage": (
            df.isnull().sum().values / len(df) * 100
        ),
        "Unique_Values": df.nunique().values
    })

    print(f"\nData Quality Report: {dataset_name}")
    display(report)

    return report

"""##  Generate data quality reports"""

orders_quality = data_quality_report(
    orders_clean, "Orders"
)

customers_quality = data_quality_report(
    customers_clean, "Customers"
)

products_quality = data_quality_report(
    products_clean, "Products"
)

