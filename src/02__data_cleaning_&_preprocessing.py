analysis_data["weekday"] = analysis_data["order_date"].dt.weekday

analysis_data["is_weekend"] = (
    analysis_data["weekday"] >= 5
)

display(analysis_data.head())

"""##  Calculate profit margin"""

analysis_data["profit_margin_pct"] = np.where(
    analysis_data["total_revenue_gbp"] != 0,
    (
        analysis_data["net_profit_gbp"] /
        analysis_data["total_revenue_gbp"]
    ) * 100,
    np.nan
)

